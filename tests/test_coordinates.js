// 仅测试已导入页面的纯计算函数，不修改坐标转换逻辑。
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../tools/coordinate_converter/app.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(0, source.indexOf('const $=')), context);
const p = context.parseCoordinate;
const f = context.formatCoordinate;
const z = context.projectionZones;
assert.ok(Math.abs(p('107°53′15.40″', 'dms', 180) - 107.88761111111111) < 1e-10);
assert.ok(Math.abs(p('-107 53.256667', 'dm', 180) + 107.88761111666667) < 1e-10);
assert.equal(p('180', 'dd', 180), 180);
assert.equal(p('-90', 'dd', 90), -90);
assert.throws(() => p('180 0 1', 'dms', 180));
assert.throws(() => p('90.1', 'dd', 90));
assert.throws(() => p('107 60 0', 'dms', 180));
assert.equal(f(12 + 59 / 60 + 59.9999 / 3600, 'dms', 2), '13°0′0.00″');
assert.equal(f(-0.00000001, 'dd', 3), '0.000');
assert.equal(z(116.4, 39.9).utm, 50);
assert.equal(z(116.4, 39.9).utmEpsg, 32650);
assert.equal(z(116.4, -39.9).utmEpsg, 32750);
assert.equal(z(5, 60).utm, 32);
assert.equal(z(15, 78).utm, 33);
assert.equal(z(0, 85).utmValid, false);
assert.equal(z(114, 30).gk, 38);
assert.equal(z(114, 30).gkCmEpsg, 4547);
console.log('坐标核心校验通过：格式解析、越界检查、进位、UTM 特例、CGCS2000 分带。');
